"""Tests for generating .env.example from starterfile ENV_VARS fields."""

from pathlib import Path

from code_starter.env_example import (
    build_env_example,
    collect_env_vars,
    write_env_example,
)
from code_starter.pseudocode_renderer import PseudocodeRenderer

BODY = """INPUT: a name
OUTPUT: a greeting
ENV_VARS:
- APP_DATA_DIR (where state is stored)
- LOG_LEVEL (default: INFO)
- FEATURE_FLAG=off (toggle the feature)
TASK: return a greeting
"""


def test_collect_env_vars_parses_bullets():
    entries = collect_env_vars({"app/src/main.py": BODY})
    assert entries == [
        ("app/src/main.py", "APP_DATA_DIR", "", "where state is stored"),
        ("app/src/main.py", "LOG_LEVEL", "INFO", ""),
        ("app/src/main.py", "FEATURE_FLAG", "off", "toggle the feature"),
    ]


def test_collect_is_empty_without_env_vars():
    assert collect_env_vars({"a.py": "INPUT: x\nTASK: y\n"}) == []


def test_build_env_example_format():
    text = build_env_example(collect_env_vars({"a.py": BODY}))
    assert "APP_DATA_DIR=" in text and "where state is stored" in text
    assert "LOG_LEVEL=INFO" in text and "default: INFO" in text
    assert "FEATURE_FLAG=off" in text
    assert text.startswith("# Generated by code_starter")


def test_write_env_example_never_clobbers(tmp_path):
    target = tmp_path / ".env.example"
    target.write_text("KEEP ME\n", encoding="utf-8")
    assert write_env_example(tmp_path, {"a.py": BODY}) is None
    assert target.read_text(encoding="utf-8") == "KEEP ME\n"

    written = write_env_example(tmp_path, {"a.py": BODY}, overwrite=True)
    assert written == target
    assert "APP_DATA_DIR" in target.read_text(encoding="utf-8")


def test_write_env_example_skips_when_no_vars(tmp_path):
    assert write_env_example(tmp_path, {"a.py": "TASK: nothing\n"}) is None
    assert not (tmp_path / ".env.example").exists()


def test_renderer_writes_env_template(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    monkeypatch.delenv("CODE_ASSISTANT_DATA_DIR", raising=False)
    monkeypatch.delenv("DATA_DIR", raising=False)
    (tmp_path / "starterfile.pseudo").write_text(
        "# REPOMAP\n\napp\n    |______ src/\n\n"
        "# DATABASES\nNONE\n\n"
        "# PSEUDOCODE\n\n## app/src/main.py\n" + BODY,
        encoding="utf-8",
    )
    renderer = PseudocodeRenderer()
    renderer.call_llm_for_conversion = lambda *_a: "def greet(name):\n    return name\n"

    assert renderer.run_mode_a()
    env_file = tmp_path / ".env.example"
    assert env_file.is_file()
    content = env_file.read_text(encoding="utf-8")
    assert "APP_DATA_DIR=" in content and "LOG_LEVEL=INFO" in content

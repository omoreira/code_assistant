"""Generate a ``.env.example`` from ``ENV_VARS`` fields in a starterfile.

A ``# PSEUDOCODE`` block may declare the environment variables the generated
code expects::

    ## app/src/main.py
    ENV_VARS:
      - APP_DATA_DIR (where state is stored)
      - LOG_LEVEL (default: INFO)

This module collects those declarations and renders a ``.env.example`` beside
the generated project so operators know which variables to provide. Only names,
defaults, and descriptions are emitted -- never secret values.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

FIELD_LABEL = re.compile(r"^\s*([A-Z][A-Z0-9_ ]*):\s*(.*)$")
BULLET = re.compile(r"^\s*[-*]\s+(.+?)\s*$")
NAME = re.compile(
    r"^([A-Za-z_][A-Za-z0-9_]*)\s*(?:[=:]\s*(.*?))?\s*(?:\(([^)]*)\))?\s*$"
)
DEFAULT = re.compile(r"default\s*[:=]\s*([^,)]+)", re.IGNORECASE)

# (file, name, default, description)
EnvEntry = Tuple[str, str, str, str]


def _env_field_lines(body: str) -> Iterable[str]:
    """Yield the lines belonging to the ``ENV_VARS`` field of one block."""
    active = False
    for line in body.splitlines():
        label = FIELD_LABEL.match(line)
        if label:
            active = " ".join(label.group(1).split()).upper() == "ENV_VARS"
            if active and label.group(2).strip():
                yield label.group(2).strip()
            continue
        if active:
            yield line


def collect_env_vars(pseudocodes: Dict[str, str]) -> List[EnvEntry]:
    """Return de-duplicated ``(file, name, default, description)`` entries."""
    collected: Dict[str, EnvEntry] = {}
    order: List[str] = []
    for path, body in pseudocodes.items():
        for raw in _env_field_lines(body):
            bullet = BULLET.match(raw)
            if not bullet:
                continue
            item = bullet.group(1)
            match = NAME.match(item)
            if not match:
                continue
            name = match.group(1)
            inline = (match.group(2) or "").strip()
            parenthetical = (match.group(3) or "").strip()
            default = ""
            default_match = DEFAULT.search(item)
            if default_match:
                default = default_match.group(1).strip()
            elif inline:
                default = inline
            description = parenthetical
            if description and DEFAULT.fullmatch(description):
                description = ""
            if name not in collected:
                order.append(name)
                collected[name] = (path, name, default, description)
    return [collected[name] for name in order]


def build_env_example(entries: List[EnvEntry]) -> str:
    """Render the ``.env.example`` text for the collected entries."""
    lines = [
        "# Generated by code_starter from starterfile.pseudo ENV_VARS fields.",
        "# Copy to .env, fill in real values, and never commit secrets.",
        "",
    ]
    for _path, name, default, description in entries:
        comment = ""
        if default:
            comment = "default: {}".format(default)
        if description:
            comment = "{}; {}".format(comment, description) if comment else description
        assignment = "{}={}".format(name, default)
        lines.append(assignment + ("  # {}".format(comment) if comment else ""))
    return "\n".join(lines) + "\n"


def write_env_example(
    project_root: Path,
    pseudocodes: Dict[str, str],
    *,
    overwrite: bool = False,
) -> Optional[Path]:
    """Write ``<project_root>/.env.example``; return its path or ``None``.

    Returns ``None`` when there are no ``ENV_VARS`` declarations, or when the
    file already exists and ``overwrite`` is false (a user's file is never
    clobbered by a regenerated template).
    """
    entries = collect_env_vars(pseudocodes)
    if not entries:
        return None
    target = Path(project_root) / ".env.example"
    if target.exists() and not overwrite:
        return None
    target.write_text(build_env_example(entries), encoding="utf-8")
    return target

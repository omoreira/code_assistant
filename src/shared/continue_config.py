"""Render a Continue.dev ``config.yaml`` snippet from the resolved LLM roles.

Continue (schema ``v1``) expects a ``config.yaml`` with ``name``/``version``/
``schema`` and a ``models`` list. We emit one entry per *distinct* resolved role
model, so a forker who edits ``config/defaults.yaml`` (or the environment) and
re-runs ``scripts/setup_hybrid_continue.sh`` gets a matching Continue setup.

Secrets are never written: API keys are referenced as Continue's env
interpolation ``${{ secrets.<ENV> }}``, using only the provider's api-key
environment variable *name*.

This module depends only on the standard library plus :mod:`shared.llm_config`.
"""

from __future__ import annotations

import argparse
from typing import List, Mapping, Optional, Sequence

from .llm_config import (
    DEFAULT_CONFIG_FILE,
    PROVIDER_OLLAMA,
    ResolvedLLM,
    resolve_llm,
)

# Roles surfaced to Continue, in priority order. The first entry becomes
# Continue's default chat model.
DEFAULT_ROLES: Sequence[str] = ("generation", "analysis", "reasoning")

# Continue role tags per resolved role.
_CONTINUE_ROLES = {
    "generation": ("chat", "edit", "apply"),
    "analysis": ("chat",),
    "reasoning": ("chat",),
}

__all__ = ["DEFAULT_ROLES", "collect_models", "render_continue_config"]


def _quote(value: object) -> str:
    """Return ``value`` as a safely double-quoted YAML scalar."""
    text = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def collect_models(
    roles: Sequence[str] = DEFAULT_ROLES,
    config_file: str = DEFAULT_CONFIG_FILE,
    env: Optional[Mapping[str, str]] = None,
) -> List[ResolvedLLM]:
    """Resolve ``roles`` and return the distinct models (first role wins).

    De-duplication key is ``(provider, model)`` so the same model configured for
    two roles is emitted once.
    """
    seen = set()
    models: List[ResolvedLLM] = []
    for role in roles:
        resolved = resolve_llm(role, config_file=config_file, env=env)
        key = (resolved.provider, resolved.model)
        if key in seen:
            continue
        seen.add(key)
        models.append(resolved)
    return models


def render_continue_config(
    roles: Sequence[str] = DEFAULT_ROLES,
    config_file: str = DEFAULT_CONFIG_FILE,
    env: Optional[Mapping[str, str]] = None,
    name: str = "code-assistant",
) -> str:
    """Render a Continue ``config.yaml`` (schema v1) as text."""
    models = collect_models(roles, config_file=config_file, env=env)

    lines = [
        "# Generated by scripts/setup_hybrid_continue.sh from the shared LLM",
        "# resolver (config/defaults.yaml < environment). Do not edit by hand.",
        "# API keys are referenced by environment variable name only.",
        f"name: {_quote(name)}",
        "version: 1.0.0",
        "schema: v1",
        "models:",
    ]
    for resolved in models:
        lines.append(f"  - name: {_quote(resolved.model)}")
        lines.append(f"    provider: {_quote(resolved.provider)}")
        lines.append(f"    model: {_quote(resolved.model)}")
        if resolved.base_url:
            lines.append(f"    apiBase: {_quote(resolved.base_url)}")
        if resolved.provider != PROVIDER_OLLAMA and resolved.api_key_env:
            lines.append(
                f'    apiKey: "${{{{ secrets.{resolved.api_key_env} }}}}"'
            )
        lines.append("    roles:")
        for tag in _CONTINUE_ROLES.get(resolved.role, ("chat",)):
            lines.append(f"      - {tag}")
    return "\n".join(lines) + "\n"


def _main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config-file", default=DEFAULT_CONFIG_FILE)
    parser.add_argument(
        "--roles",
        default=",".join(DEFAULT_ROLES),
        help="comma-separated roles (default: %(default)s)",
    )
    parser.add_argument("--name", default="code-assistant")
    args = parser.parse_args(argv)
    roles = tuple(r.strip() for r in args.roles.split(",") if r.strip())
    print(
        render_continue_config(
            roles=roles, config_file=args.config_file, name=args.name
        ),
        end="",
    )
    return 0


if __name__ == "__main__":  # pragma: no cover - manual/tooling entry point
    raise SystemExit(_main())
